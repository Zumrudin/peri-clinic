async function upsertPriceItem(procedureId, sort, item) {
  const existing = (
    await get(`/items/price_items?filter[procedure][_eq]=${procedureId}&filter[name][_eq]=${encodeURIComponent(item.name)}&limit=1`)
  )[0];
  const payload = { procedure: procedureId, sort, ...item };
  if (existing) {
    await patch(`/items/price_items/${existing.id}`, payload);
  } else {
    await post('/items/price_items', payload);
    log('  created', item.name);
  }
}

async function main() {
  for (const { slug, items } of DATA) {
    const proc = (await get(`/items/procedures?filter[slug][_eq]=${slug}&fields=id&limit=1`))[0];
    if (!proc) {
      log('SKIP — no procedure found for slug', slug);
      continue;
    }
    log('seeding prices for', slug, `(${items.length} rows)`);
    let sort = 1;
    for (const item of items) {
      await upsertPriceItem(proc.id, sort++, item);
    }
  }
  log('done');
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
