import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';

const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
try {
  const page = await browser.newPage({ viewport: { width: 375, height: 900 }, hasTouch: true });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(process.argv[2] || 'http://127.0.0.1:4321');
  const cookie = page.locator('[data-cookie-accept]');
  if (await cookie.isVisible()) await cookie.click();
  const root = page.locator('[data-home-reels]');
  await root.scrollIntoViewIfNeeded();
  const cards = root.locator('[data-reel]');
  const first = cards.first();
  await page.waitForFunction(() => document.querySelector('[data-reel-video]').currentTime > .1);
  assert.equal(await first.getAttribute('data-caption-hidden'), null, 'caption initially visible');
  await first.locator('[data-reel-toggle]').click();
  await page.waitForTimeout(1700);
  assert.equal(await first.getAttribute('data-caption-hidden'), null, 'pause suspends caption timer');
  await first.locator('[data-reel-toggle]').click();
  await page.waitForFunction(() => document.querySelector('[data-reel]').hasAttribute('data-caption-hidden'));
  const caption = first.locator('[data-reel-caption-toggle]');
  await caption.click({ position: { x: 100, y: 100 } });
  assert.equal(await caption.getAttribute('aria-expanded'), 'true');
  await page.waitForTimeout(1700);
  assert.equal(await caption.getAttribute('aria-expanded'), 'true', 'manual reveal persists');
  await caption.click({ position: { x: 100, y: 100 } });
  assert.equal(await caption.getAttribute('aria-expanded'), 'false');
  await first.locator('[data-reel-mute]').click();
  assert.equal(await caption.getAttribute('aria-expanded'), 'false', 'controls do not toggle caption');
  assert.equal(await first.locator('video').evaluate(v => v.muted), false);
  await first.locator('[data-reel-mute]').click();
  await first.locator('video').evaluate(v => { v.currentTime = v.duration - .3; });
  await page.waitForFunction(() => document.querySelectorAll('[data-reels-dot]')[1].getAttribute('aria-current') === 'true');
  await page.waitForFunction(() => !document.querySelectorAll('[data-reel-video]')[1].paused);
  assert.equal(await first.locator('video').evaluate(v => v.ended && v.paused && !v.loop), true);
  await page.waitForFunction(() => document.querySelectorAll('[data-reel]')[1].hasAttribute('data-caption-hidden'));
  const rail = root.locator('[data-reels-rail]');
  await rail.focus();
  await page.keyboard.press('End');
  await page.waitForFunction(() => ![...document.querySelectorAll('[data-reel-video]')].at(-1).paused);
  await cards.last().locator('video').evaluate(v => { v.currentTime = v.duration - .3; });
  await page.waitForFunction(() => [...document.querySelectorAll('[data-reel-video]')].at(-1).ended);
  await page.evaluate(() => window.dispatchEvent(new Event('scroll')));
  await page.waitForTimeout(300);
  assert.equal(await cards.last().locator('video').evaluate(v => v.paused && v.ended), true, 'last clip stays ended');
  await cards.last().locator('[data-reel-toggle]').click();
  await page.waitForFunction(() => { const v = [...document.querySelectorAll('[data-reel-video]')].at(-1); return !v.paused && v.currentTime < 3; });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await cards.last().locator('[data-reel-caption-toggle]').click({ position: { x: 100, y: 100 } });
  assert.equal(await cards.last().locator('.reel-caption').evaluate(el => getComputedStyle(el).transform), 'none');
  assert.deepEqual(errors, []);
  console.log('PASS: caption delay, pause/resume, manual toggle, independent controls, real ended advance, final stop/replay, reduced motion; no browser errors.');
} finally { await browser.close(); }
